    private void btnPaidActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPaidActionPerformed
        int selectedRow = tblRenters.getSelectedRow();

if (selectedRow == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Please select a customer first."
    );
    return;
}

int modelRow = tblRenters.convertRowIndexToModel(selectedRow);
renterController.markPaid(modelRow);
    }//GEN-LAST:event_btnPaidActionPerformed

    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActionPerformed
       
        int selectedRow = tblRenters.getSelectedRow();

if (selectedRow == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Please select a customer to remove."
    );
    return;
}

int modelRow = tblRenters.convertRowIndexToModel(selectedRow);
renterController.removeRenter(modelRow);
        
    }//GEN-LAST:event_btnRemoveActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        
        String name = txtCustomerName.getText().trim();
String address = txtCustomerAddress.getText().trim();

if (name.isEmpty() || address.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Please enter the customer name and address."
    );
    return;
}

int cottages = Integer.parseInt(
    cmbCustomerCottage.getSelectedItem().toString()
);

String size = cmbCottageSize.getSelectedItem().toString();

int price = Integer.parseInt(
    cmbCottagePrice.getSelectedItem().toString()
);

renterController.addRenter(
    name, address, cottages, size, price
);

txtCustomerName.setText("");
txtCustomerAddress.setText("");
cmbCustomerCottage.setSelectedIndex(0);
cmbCottageSize.setSelectedIndex(0);
txtCustomerName.requestFocus();
        
    }//GEN-LAST:event_btnAddActionPerformed

