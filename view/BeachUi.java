    private void updatePrice() {
    int index = cmbCottageSize.getSelectedIndex();

    int[] prices = {300, 500, 800};

    if (index >= 0) {
        cmbCottagePrice.setSelectedItem(
            String.valueOf(prices[index])
        );
    }
}

